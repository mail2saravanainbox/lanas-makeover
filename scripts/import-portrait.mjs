/**
 * ─────────────────────────────────────────────────────────────────────────────
 *  IMPORT LANA'S PORTRAIT
 * ─────────────────────────────────────────────────────────────────────────────
 *  Optimises the single photograph of the artist herself and records what the
 *  UI needs to render it well.
 *
 *  Separate from `import:portfolio` on purpose. That script fills the ARCHIVE —
 *  photographs of Lana's work, which are browsable, filterable and captioned as
 *  work. A portrait of the artist is not work; putting it through the same
 *  pipeline would file the founder of the business as a bridal look in her own
 *  gallery.
 *
 *    content/lana/portrait.*  →  public/lana/portrait.webp
 *                             →  src/content/portrait.json
 *
 *  The JSON carries the intrinsic dimensions and a real blur placeholder
 *  generated from the photograph itself, so the frame reserves its space
 *  before the image arrives (no layout shift) and fades up from her own
 *  colours rather than a grey box.
 *
 *  Run: node scripts/import-portrait.mjs
 * ─────────────────────────────────────────────────────────────────────────────
 */
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC_DIR = "content/lana";
const OUT_IMG = "public/lana/portrait.webp";
const OUT_JSON = "src/content/portrait.json";

/** Matches the portfolio pipeline, minus the 2000px archive width: this is a
 *  portrait rendered at most ~600 CSS px, so 1400 covers 2× DPR with room. */
const MAX_WIDTH = 1400;
const QUALITY = 82;

const EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".tif", ".tiff"]);

const files = (await readdir(SRC_DIR)).filter((f) => EXT.has(path.extname(f).toLowerCase()));
if (files.length === 0) {
  console.error(`No image found in ${SRC_DIR}/. Drop the portrait there and re-run.`);
  process.exit(1);
}
if (files.length > 1) {
  console.error(`Expected one portrait in ${SRC_DIR}/, found ${files.length}: ${files.join(", ")}`);
  process.exit(1);
}

const source = path.join(SRC_DIR, files[0]);
await mkdir(path.dirname(OUT_IMG), { recursive: true });

const input = sharp(source).rotate(); // honour EXIF orientation
const meta = await input.metadata();

const info = await input
  .clone()
  .resize({ width: Math.min(meta.width ?? MAX_WIDTH, MAX_WIDTH), withoutEnlargement: true })
  .webp({ quality: QUALITY })
  .toFile(OUT_IMG);

const blur = await input
  .clone()
  .resize({ width: 20 })
  .webp({ quality: 40 })
  .toBuffer();

await writeFile(
  OUT_JSON,
  `${JSON.stringify(
    {
      _comment:
        "Generated by scripts/import-portrait.mjs from content/lana/. Do not edit by hand.",
      generatedAt: new Date().toISOString(),
      src: `/${OUT_IMG.replace(/^public\//, "")}`,
      width: info.width,
      height: info.height,
      blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    },
    null,
    2,
  )}\n`,
);

console.log(`✓ ${source}  →  ${OUT_IMG}  ${info.width}×${info.height}  ${(info.size / 1024).toFixed(0)} KB`);
console.log(`✓ ${OUT_JSON}`);
